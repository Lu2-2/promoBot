package promobot.model.amazon;

public class Medium{
	private int width;
	private String url;
	private int height;

	public void setWidth(int width) {
		this.width = width;
	}

	public void setUrl(String url) {
		this.url = url;
	}

	public void setHeight(int height) {
		this.height = height;
	}

	public int getWidth(){
		return width;
	}

	public String getUrl(){
		return url;
	}

	public int getHeight(){
		return height;
	}
}
